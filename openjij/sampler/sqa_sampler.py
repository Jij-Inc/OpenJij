# Trotter coupling J_perp = -1/2 ln tanh(beta * Gamma * (1 - s) / M) of the
# default schedule. It grows geometrically from `coupling_min` to
# `coupling_max`, which are chosen from the energy landscape by
# `trotter_coupling_range`:
#
# - coupling_min rises from _COUPLING_MIN_RANGE[0] to [1] as the dominance
#   (median over spins of the largest coefficient divided by the RMS of all
#   coefficients of the spin) rises over _DOMINANCE_RANGE. Frustrated
#   spin glasses (low dominance) need nearly independent replicas early on;
#   problems whose spins are ruled by one term (a field or a strong bond)
#   gain from coupled replicas early on.
# - coupling_max rises from _COUPLING_MAX_RANGE[0] to [1] as the pair-move
#   fraction (spins of low-energy states whose cheapest flip together with
#   a neighbour costs less than half of their single flip) rises over
#   _PAIR_MOVE_RANGE. Tall and narrow barriers, e.g. global constraints,
#   need strongly coupled replicas at the end; otherwise strong coupling
#   locks the replicas onto one configuration and loses diversity.
# - Both are multiplied by a factor that falls from 1 to _ZERO_MODE_SCALE as
#   the zero-mode fraction (spins of low-energy states that flip at no
#   energy cost) rises over _ZERO_MODE_RANGE. In degenerate landscapes,
#   e.g. lattice spin glasses with +-1 couplings, the search moves along
#   zero-energy flips, which a Trotter coupling suppresses.
_DOMINANCE_RANGE = (0.4, 0.9)
_COUPLING_MIN_RANGE = (0.01, 0.2)
_PAIR_MOVE_RANGE = (0.3, 0.8)
_COUPLING_MAX_RANGE = (0.5, 2.0)
_ZERO_MODE_RANGE = (0.003, 0.03)
_ZERO_MODE_SCALE = 0.1

# Upper bound of the memory used by the systems that run concurrently.
_MAX_SYSTEMS_MEMORY = 1 << 30


class SQASampler(BaseSampler):
    """Sampler with Simulated Quantum Annealing (SQA).

    Inherits from :class:`openjij.sampler.sampler.BaseSampler`.
    Hamiltonian

    .. math::

        H(s) = s H_p + \\Gamma (1-s)\\sum_i \\sigma_i^x

    where :math:`H_p` is the problem Hamiltonian we want to solve.
    The quantum Monte Carlo simulation uses the Suzuki-Trotter
    decomposition with ``trotter`` slices. Every slice feels the problem
    Hamiltonian at inverse temperature :math:`s\\beta/M` and neighbouring
    slices are coupled ferromagnetically with
    :math:`J_\\perp = -\\frac12\\ln\\tanh(\\beta\\Gamma(1-s)/M)`.

    Unless ``schedule``, ``beta`` or ``gamma`` is given, the annealing
    schedule is generated by :func:`geometric_sqa_schedule`: the classical
    inverse temperature of every slice follows the automatic schedule of
    :class:`openjij.SASampler` (estimated from the coefficients of the
    problem), and the transverse field decreases such that
    :math:`J_\\perp` grows geometrically. Both ends of :math:`J_\\perp` are
    chosen from the energy landscape (:func:`trotter_coupling_range`): weak
    for frustrated spin glasses, where nearly independent replicas work
    best, and stronger for problems with rigid local structure or tall and
    narrow barriers such as global constraints. The transverse field stays
    finite at the end of the annealing.

    Reads run in parallel on ``num_threads`` threads.

    Args:
        beta (float): Inverse temperature (legacy schedule).
        gamma (float): Amplitude of quantum fluctuation (legacy schedule).
        trotter (int): Trotter number.
        num_sweeps (int): number of sweeps
        schedule (list): schedule list
        num_reads (int): Number of iterations.
        schedule_info (dict): Information about a annealing schedule.

    Raises:
        ValueError: If the schedule violates as below.
        - not list or numpy.array.
        - schedule range is '0 <= s <= 1'.
    """

    @property
    def parameters(self):
        return {
            "beta": ["parameters"],
            "gamma": ["parameters"],
            "trotter": ["parameters"],
            "beta_min": ["parameters"],
            "beta_max": ["parameters"],
        }

    def __init__(self):

        # Set default parameters
        # beta and gamma are None: the schedule is generated automatically.
        beta = None
        gamma = None
        beta_min = None
        beta_max = None
        num_sweeps = 1000
        num_reads = 1
        schedule = None
        trotter = 8

        self._default_params = {
            "beta": beta,
            "gamma": gamma,
            "beta_min": beta_min,
            "beta_max": beta_max,
            "num_sweeps": num_sweeps,
            "schedule": schedule,
            "trotter": trotter,
            "num_reads": num_reads,
        }

        self._params = dict(self._default_params)

        self._make_system = {
            "singlespinflip": cxxjij.system.make_transverse_ising,
            "trotterclusterflip": cxxjij.system.make_transverse_ising,
        }
        self._algorithm = {
            "singlespinflip": cxxjij.algorithm.Algorithm_SingleSpinFlip_run_parallel,
            "trotterclusterflip": cxxjij.algorithm.Algorithm_TrotterClusterFlip_run_parallel,
        }

    def _convert_validation_schedule(self, schedule, beta):
        if not isinstance(schedule, (list, np.ndarray)):
            raise ValueError("schedule should be list or numpy.array")

        if isinstance(schedule[0], cxxjij.utility.TransverseFieldSchedule):
            return schedule

        # schedule validation  0 <= s <= 1
        sch = np.array(schedule).T[0]
        if not np.all((0 <= sch) & (sch <= 1)):
            raise ValueError("schedule range is '0 <= s <= 1'.")

        if len(schedule[0]) == 2:
            # schedule element: (s, one_mc_step) with beta fixed
            # convert to list of cxxjij.utility.TransverseFieldSchedule
            cxxjij_schedule = []
            for s, one_mc_step in schedule:
                _schedule = cxxjij.utility.TransverseFieldSchedule()
                _schedule.one_mc_step = one_mc_step
                _schedule.updater_parameter.beta = beta
                _schedule.updater_parameter.s = s
                cxxjij_schedule.append(_schedule)
            return cxxjij_schedule
        elif len(schedule[0]) == 3:
            # schedule element: (s, beta, one_mc_step)
            # convert to list of cxxjij.utility.TransverseFieldSchedule
            cxxjij_schedule = []
            for s, _beta, one_mc_step in schedule:
                _schedule = cxxjij.utility.TransverseFieldSchedule()
                _schedule.one_mc_step = one_mc_step
                _schedule.updater_parameter.beta = _beta
                _schedule.updater_parameter.s = s
                cxxjij_schedule.append(_schedule)
            return cxxjij_schedule
        else:
            raise ValueError(
                """schedule is list of tuple or list
                (annealing parameter s : float, step_length : int) or
                (annealing parameter s : float, beta: float, step_length : int)
                """
            )

    def _get_result(self, system, model):
        state, info = super()._get_result(system, model)

        q_state = system.trotter_spins[:-1].T.astype(int)
        c_energies = [get_state_and_energy(model, state)[1] for state in q_state]
        info["trotter_state"] = q_state
        info["trotter_energies"] = c_energies

        return state, info

    def sample(
        self,
        bqm: Union[
            "openjij.model.model.BinaryQuadraticModel", dimod.BinaryQuadraticModel
        ],
        beta: Optional[float] = None,
        gamma: Optional[float] = None,
        num_sweeps: Optional[int] = None,
        schedule: Optional[list] = None,
        trotter: Optional[int] = None,
        num_reads: Optional[int] = None,
        initial_state: Optional[Union[list, dict]] = None,
        updater: Optional[str] = None,
        sparse: Optional[bool] = None,
        reinitialize_state: Optional[bool] = None,
        seed: Optional[int] = None,
        *,
        beta_min: Optional[float] = None,
        beta_max: Optional[float] = None,
        coupling_min: Optional[float] = None,
        coupling_max: Optional[float] = None,
        num_threads: Optional[int] = None,
    ) -> "openjij.sampler.response.Response":
        """Sampling from the Ising model.

        The annealing schedule is chosen as follows.

        - ``schedule`` is given: the custom schedule.
        - ``beta`` or ``gamma`` is given: the legacy schedule, i.e. fixed
          ``beta`` (default 5) and ``s`` following
          :func:`quartic_ising_schedule` from 0 to 1.
        - otherwise: :func:`geometric_sqa_schedule`. ``beta_min`` and
          ``beta_max`` override the estimated range of the classical inverse
          temperature of each Trotter slice, and ``coupling_min`` and
          ``coupling_max`` the range of the Trotter coupling chosen from the
          energy landscape (:func:`trotter_coupling_range`).

        Args:
            bqm (openjij.BinaryQuadraticModel) binary quadratic model
            beta (float, optional): inverse temperature of the legacy schedule.
            gamma (float, optional): strength of transverse field. Defaults to 1 for custom and legacy schedules.
            num_sweeps (int, optional): number of sweeps. Defaults to 1000.
            schedule (list[list[float, int]], optional): List of annealing parameter. Defaults to None.
            trotter (int): Trotter number. Defaults to 8.
            num_reads (int, optional): number of sampling. Defaults to 1.
            initial_state (list[int], optional): Initial state. Defaults to None.
            updater (str, optional): update method, "single spin flip" (default)
                or "trotter cluster flip". The latter flips segments of Trotter
                copies at once and keeps the replicas moving when the Trotter
                coupling is strong (e.g. near s = 1 in reverse annealing).
            sparse (bool): use sparse matrix or not.
            reinitialize_state (bool, optional): Re-initilization at each sampling. Defaults to True.
                If False, reads run sequentially, each starting from the previous final state.
            seed (int, optional): seed for reproducible batches with a distinct random seed per read.
            beta_min (float, optional): initial classical inverse temperature per Trotter slice
                of the automatic schedule.
            beta_max (float, optional): final classical inverse temperature per Trotter slice
                of the automatic schedule.
            coupling_min (float, optional): initial Trotter coupling of the automatic schedule.
            coupling_max (float, optional): final Trotter coupling of the automatic schedule.
            num_threads (int, optional): number of threads that run reads in parallel.
                Defaults to ``OMP_NUM_THREADS`` if set, otherwise the number of CPUs.
                Results do not depend on the number of threads.

        Raises:
            ValueError:

        Returns:
            :class:`openjij.sampler.response.Response`: results

        Examples:

            for Ising case::

                >>> h = {0: -1, 1: -1, 2: 1, 3: 1}
                >>> J = {(0, 1): -1, (3, 4): -1}
                >>> sampler = openjij.SQASampler()
                >>> res = sampler.sample_ising(h, J)

            for QUBO case::

                >>> Q = {(0, 0): -1, (1, 1): -1, (2, 2): 1, (3, 3): 1, (4, 4): 1, (0, 1): -1, (3, 4): 1}
                >>> sampler = openjij.SQASampler()
                >>> res = sampler.sample_qubo(Q)
        """

        # Set default parameters
        if sparse is None:
            sparse = True
        if reinitialize_state is None:
            reinitialize_state = True
        if updater is None:
            updater = "single spin flip"

        if isinstance(bqm, dimod.BinaryQuadraticModel):
            bqm = oj.model.model.BinaryQuadraticModel(
                dict(bqm.linear), dict(bqm.quadratic), bqm.offset, bqm.vartype, sparse=sparse
            )

        if sparse and not bqm.sparse:
            bqm = oj.model.model.BinaryQuadraticModel(
                bqm.linear, bqm.quadratic, bqm.offset, bqm.vartype, sparse=True
            )

        ising_graph, offset = bqm.get_cxxjij_ising_graph()

        self._set_params(
            beta=beta,
            gamma=gamma,
            beta_min=beta_min,
            beta_max=beta_max,
            num_sweeps=num_sweeps,
            num_reads=num_reads,
            trotter=trotter,
            schedule=schedule,
        )

        trotter = int(self._params["trotter"])
        if trotter < 2:
            raise ValueError("trotter must be equal or larger than 2.")
        if self._params["num_reads"] < 1:
            raise ValueError("num_reads must be positive.")

        num_threads = _resolve_num_threads(num_threads)

        # choose updater -------------------------------------------
        _updater_name = updater.lower().replace("_", "").replace(" ", "")
        if _updater_name not in self._algorithm:
            raise ValueError('updater is one of "single spin flip" or "trotter cluster flip"')
        algorithm = self._algorithm[_updater_name]
        make_system = self._make_system[_updater_name]
        # ------------------------------------------- choose updater

        # set annealing schedule -------------------------------
        use_legacy = self._params["beta"] is not None or self._params["gamma"] is not None
        automatic = (self._params["beta_min"], self._params["beta_max"], coupling_min, coupling_max)
        if any(x is not None for x in automatic) and (self._params["schedule"] or use_legacy):
            raise ValueError(
                "beta_min, beta_max, coupling_min and coupling_max cannot be combined with schedule, beta or gamma."
            )

        system_gamma = 1.0 if self._params["gamma"] is None else self._params["gamma"]
        if self._params["schedule"]:
            legacy_beta = 5.0 if self._params["beta"] is None else self._params["beta"]
            self._params["schedule"] = self._convert_validation_schedule(self._params["schedule"], legacy_beta)
            self.schedule_info = {"schedule": "custom schedule"}
        elif use_legacy:
            legacy_beta = 5.0 if self._params["beta"] is None else self._params["beta"]
            self._params["schedule"], beta_gamma = quartic_ising_schedule(
                model=bqm, beta=legacy_beta, gamma=system_gamma, num_sweeps=self._params["num_sweeps"]
            )
            self.schedule_info = {
                "beta": beta_gamma[0],
                "gamma": beta_gamma[1],
                "num_sweeps": self._params["num_sweeps"],
            }
        else:
            self._params["schedule"], self.schedule_info = geometric_sqa_schedule(
                ising_graph,
                trotter=trotter,
                num_sweeps=self._params["num_sweeps"],
                beta_min=self._params["beta_min"],
                beta_max=self._params["beta_max"],
                coupling_min=coupling_min,
                coupling_max=coupling_max,
                gamma=system_gamma,
                from_qubo=bqm.vartype == BINARY,
            )
        # ------------------------------- set annealing schedule

        # make init state generator --------------------------------
        num_spins = ising_graph.size()
        if initial_state is None:

            def init_generator(read_seed):
                rng = np.random.default_rng(read_seed)
                return rng.choice([-1, 1], size=(trotter, num_spins)).tolist()

        else:
            if isinstance(initial_state, dict):
                initial_state = [initial_state[k] for k in bqm.variables]

            # convert to spin variable
            if bqm.vartype == BINARY:
                temp_initial_state = []
                for v in initial_state:
                    if v != 0 and v != 1:
                        raise RuntimeError(
                            "The initial variables must be 0 or 1 if vartype is BINARY."
                        )
                    temp_initial_state.append(2 * v - 1)

                initial_state = temp_initial_state

            # validate initial_state size
            if len(initial_state) != num_spins:
                raise ValueError(
                    "the size of the initial state should be {}".format(num_spins)
                )

            trotter_init_state = [[int(v) for v in initial_state] for _ in range(trotter)]

            def init_generator(read_seed):
                return trotter_init_state

        # -------------------------------- make init state generator

        response = self._parallel_sampling(
            bqm,
            ising_graph,
            init_generator,
            make_system,
            algorithm,
            system_gamma,
            reinitialize_state,
            _read_seeds(seed, self._params["num_reads"]),
            num_threads,
        )

        response.info["schedule"] = self.schedule_info

        return response

    def _parallel_sampling(
        self,
        model,
        ising_graph,
        init_generator,
        make_system,
        algorithm,
        gamma,
        reinitialize_state,
        read_seeds,
        num_threads,
    ):
        """Run the reads on concurrent systems and collect the results.

        Each read owns a random seed, so the samples do not depend on
        ``num_threads``. With ``reinitialize_state=False`` every read continues
        from the final state of the previous one, so the reads run one by one.
        """
        num_reads = len(read_seeds)
        schedule = self._params["schedule"]

        if reinitialize_state:
            chunk_size = _concurrent_systems(
                ising_graph, self._params["trotter"], num_reads, num_threads
            )
        else:
            chunk_size = 1

        systems = []
        states, energies = [], []
        system_info = {"system": []}
        execution_time = []

        start_time = time.perf_counter()
        for start in range(0, num_reads, chunk_size):
            seeds = read_seeds[start : start + chunk_size]
            while len(systems) < len(seeds):
                read_seed = seeds[len(systems)]
                systems.append(make_system(init_generator(read_seed), ising_graph, gamma))
            if reinitialize_state:
                for system, read_seed in zip(systems, seeds):
                    system.reset_spins(init_generator(read_seed))

            chunk_start = time.perf_counter()
            algorithm(systems[: len(seeds)], seeds, schedule, min(num_threads, len(seeds)))
            chunk_time = time.perf_counter() - chunk_start
            execution_time.extend([chunk_time / len(seeds)] * len(seeds))

            for system in systems[: len(seeds)]:
                result_state, _sys_info = self._get_result(system, model)
                result_state, energy = get_state_and_energy(model, result_state, 0)
                states.append(result_state)
                energies.append(energy)
                if _sys_info:
                    system_info["system"].append(_sys_info)
        sampling_time = time.perf_counter() - start_time

        response = oj.sampler.response.Response.from_samples(
            states, model.vartype, energies, info=system_info
        )

        response.info["sampling_time"] = sampling_time * 10**6  # micro sec
        # wall-clock time per read; reads in a chunk run concurrently.
        response.info["execution_time"] = np.mean(execution_time) * 10**6  # micro sec
        response.info["list_exec_times"] = np.array(execution_time) * 10**6  # micro sec

        return response

    def _annealing_schedule_setting(
        self, model, beta=None, gamma=None, num_sweeps=None, schedule=None
    ):
        """Set the legacy schedule (used by :class:`CSQASampler`)."""
        if schedule:
            self._params["schedule"] = self._convert_validation_schedule(schedule, beta)
            self.schedule_info = {"schedule": "custom schedule"}
        else:

            self._params["schedule"], beta_gamma = quartic_ising_schedule(
                model=model, beta=beta, gamma=gamma, num_sweeps=num_sweeps
            )
            self.schedule_info = {
                "beta": beta_gamma[0],
                "gamma": beta_gamma[1],
                "num_sweeps": num_sweeps,
            }


def _resolve_num_threads(num_threads):
    if num_threads is None:
        env = os.environ.get("OMP_NUM_THREADS", "")
        try:
            num_threads = int(env.split(",")[0])
        except ValueError:
            num_threads = 0
        if num_threads < 1:
            num_threads = os.cpu_count() or 1
    if int(num_threads) != num_threads or num_threads < 1:
        raise ValueError("num_threads must be a positive integer.")
    return int(num_threads)


def _read_seeds(seed, num_reads):
    """Distinct per-read seeds; reproducible for a given ``seed``."""
    if seed is None:
        return [int(x) for x in np.random.default_rng().integers(0, 2**32, size=num_reads)]
    # Xorshift takes a 32-bit seed. An odd step visits each seed once before
    # wrapping, starting with the original seed for the first read.
    seed_step = 2 * int(np.random.default_rng(seed).integers(2**31)) + 1
    return [(int(seed) + read * seed_step) % 2**32 for read in range(num_reads)]


def _concurrent_systems(ising_graph, trotter, num_reads, num_threads):
    """Number of systems that run concurrently.

    A few systems per thread let fast cores pick up more reads (dynamic
    scheduling). Every system holds a copy of the interactions, so the
    total memory is bounded.
    """
    num_spins = ising_graph.size() + 1
    if isinstance(ising_graph, cxxjij.graph.Dense):
        interaction_bytes = num_spins * num_spins * 8
    else:
        interaction_bytes = ising_graph.get_interactions().nnz * 12 + num_spins * 4
    trotter_bytes = 3 * num_spins * trotter * 8
    by_memory = max(1, _MAX_SYSTEMS_MEMORY // (interaction_bytes + trotter_bytes))
    return int(max(1, min(num_reads, 4 * num_threads, by_memory)))


def _log_interp(x, xs, ys):
    """Interpolate log(y) linearly in x, constant outside ``xs``."""
    if x <= xs[0]:
        return float(ys[0])
    if x >= xs[1]:
        return float(ys[1])
    return float(np.exp(np.interp(x, xs, np.log(ys))))


def _dominance(cxxgraph, *, from_qubo):
    """Median over spins of the largest coefficient over the RMS of all of them.

    It uses the statistics of the automatic SA schedule. Spins whose
    coefficients are all zero are skipped; returns 1 if all are.
    """
    scaled_sigma, scales, _ = _ising_beta_range_statistics(cxxgraph, from_qubo=from_qubo)
    active = (scales > 0) & (scaled_sigma > 0)
    if not np.any(active):
        return 1.0
    return float(np.median(1.0 / scaled_sigma[active]))


def _low_energy_moves(cxxgraph, *, from_qubo, num_reads=4, num_sweeps=100):
    """Pair-move and zero-mode fractions of low-energy states.

    Short SA runs (fixed seeds, so the result depends only on the problem)
    give low-energy states. For each spin ``i`` with a positive flip cost
    ``dE_i`` the cheapest flip together with a neighbour ``j`` costs
    ``dE_i + dE_j + 4 J_ij s_i s_j``. The spin counts as a pair move if that
    is below ``dE_i / 2``: the barrier of the single flip is much taller
    than the cost of the two-spin move. Spins with ``dE_i = 0`` are zero
    modes. Returns both fractions averaged over the runs.
    """
    n = cxxgraph.size()
    if n < 2:
        return 0.0, 0.0
    # Couplings in CSR form (indptr, cols, values) without the diagonal.
    interactions = cxxgraph.get_interactions()
    if isinstance(interactions, np.ndarray):
        fields = np.array(interactions[:n, n], dtype=float)
        dense = np.array(interactions[:n, :n], dtype=float)
        np.fill_diagonal(dense, 0.0)
        rows, cols = np.nonzero(dense)
        values = dense[rows, cols]
    else:
        coo = interactions.tocoo()
        is_field = (coo.col == n) & (coo.row < n)
        fields = np.zeros(n)
        np.add.at(fields, coo.row[is_field], coo.data[is_field])
        keep = (coo.row < n) & (coo.col < n) & (coo.row != coo.col) & (coo.data != 0)
        order = np.lexsort((coo.col[keep], coo.row[keep]))
        rows, cols, values = coo.row[keep][order], coo.col[keep][order], np.asarray(coo.data[keep][order], float)
    if values.size == 0:
        return 0.0, 0.0
    counts = np.bincount(rows, minlength=n)
    nonempty = counts > 0
    starts = (np.cumsum(counts) - counts)[nonempty]

    schedule, _ = geometric_ising_beta_schedule(
        cxxgraph, num_sweeps=num_sweeps, from_qubo=from_qubo, use_quantiles=True
    )
    pair_moves, zero_modes = [], []
    for read in range(num_reads):
        init = np.random.default_rng(read).choice([-1, 1], size=n)
        system = cxxjij.system.make_classical_ising(init.tolist(), cxxgraph)
        cxxjij.algorithm.Algorithm_SingleSpinFlip_run(system, read, schedule)
        spins = np.asarray(cxxjij.result.get_solution(system), dtype=float)
        local_fields = np.bincount(rows, weights=values * spins[cols], minlength=n) + fields
        single = -2.0 * spins * local_fields
        pair = single[rows] + single[cols] + 4.0 * values * spins[rows] * spins[cols]
        cheapest = np.full(n, np.inf)
        cheapest[nonempty] = np.minimum.reduceat(pair, starts)
        positive = single[single > 0]
        if positive.size == 0:
            pair_moves.append(0.0)
            zero_modes.append(0.0)
            continue
        tolerance = 1e-9 * np.median(positive)
        active = single > tolerance
        pair_moves.append(float(np.mean(np.maximum(cheapest[active], 0.0) < 0.5 * single[active])))
        zero_modes.append(float(np.mean(np.abs(single) <= tolerance)))
    return float(np.mean(pair_moves)), float(np.mean(zero_modes))


def trotter_coupling_range(cxxgraph, *, from_qubo=False):
    """Initial and final Trotter coupling of the default schedule.

    Both are chosen from the energy landscape of the problem.

    - ``coupling_min`` grows with the dominance, the median over spins of
      ``max_j |c_ij| / sqrt(sum_j c_ij^2)`` over the coefficients ``c_ij``
      (couplings and field) of spin ``i``; the automatic SA schedule uses
      the same statistics. In frustrated spin glasses many comparable
      terms act on every spin and the replicas must stay nearly
      independent early on. When one term rules each spin, rigid local
      structures form early and coupled replicas move them together.
    - ``coupling_max`` grows with the pair-move fraction
      (``_low_energy_moves``): the share of spins of low-energy states
      whose single flip is much more expensive than a flip together with a
      neighbour, as with global constraints. Such tall and narrow barriers
      need strongly coupled replicas at the end. Otherwise strong coupling
      at the end locks the replicas onto one configuration.
    - Both shrink as the zero-mode fraction grows: the share of spins of
      low-energy states that flip at no cost. Degenerate landscapes, such as
      lattice spin glasses with +-1 couplings, are searched through
      zero-energy flips, and the Trotter coupling would suppress them.

    Args:
        cxxgraph: Ising graph, ``Dense`` or ``CSRSparse``.
        from_qubo (bool): the graph was converted from a BINARY model.

    Returns:
        ``(coupling_min, coupling_max)`` and a dict with the dominance, the
        pair-move fraction and the zero-mode fraction.
    """
    dominance = _dominance(cxxgraph, from_qubo=from_qubo)
    pair_moves, zero_modes = _low_energy_moves(cxxgraph, from_qubo=from_qubo)
    scale = _log_interp(zero_modes, _ZERO_MODE_RANGE, (1.0, _ZERO_MODE_SCALE))
    coupling_min = scale * _log_interp(dominance, _DOMINANCE_RANGE, _COUPLING_MIN_RANGE)
    coupling_max = scale * _log_interp(pair_moves, _PAIR_MOVE_RANGE, _COUPLING_MAX_RANGE)
    stats = {"dominance": dominance, "pair_move_fraction": pair_moves, "zero_mode_fraction": zero_modes}
    return (coupling_min, coupling_max), stats


def geometric_sqa_schedule(
    cxxgraph: Union[openjij.cxxjij.graph.Dense, openjij.cxxjij.graph.CSRSparse],
    trotter: int,
    num_sweeps: int = 1000,
    beta_min: Optional[float] = None,
    beta_max: Optional[float] = None,
    *,
    coupling_min: Optional[float] = None,
    coupling_max: Optional[float] = None,
    gamma: float = 1.0,
    from_qubo: bool = False,
):
    """Default SQA schedule: classical and quantum terms annealed together.

    Write the Trotterized weight of the replicas
    :math:`\\sigma_1, \\dots, \\sigma_M` as

    .. math::

        \\exp\\Big(-\\beta_{\\mathrm{cl}} \\sum_t H_p(\\sigma_t)
        + J_\\perp \\sum_{t,i} \\sigma_{i,t}\\sigma_{i,t+1}\\Big),

    with :math:`\\beta_{\\mathrm{cl}} = s\\beta/M` and
    :math:`J_\\perp = -\\frac12\\ln\\tanh(\\beta\\Gamma(1-s)/M)`.
    The schedule controls both energy scales directly.

    - :math:`\\beta_{\\mathrm{cl}}` follows the automatic SA schedule
      (:func:`openjij.sampler.sa_sampler.geometric_ising_beta_schedule`),
      which is estimated from the coefficients of the problem, so each slice
      is cooled like an SA run.
    - :math:`J_\\perp` grows geometrically from ``coupling_min`` to
      ``coupling_max``; the transverse field in units of the slice
      temperature is :math:`\\beta_{\\mathrm{cl}}\\Gamma_{\\mathrm{eff}} =
      \\operatorname{artanh} e^{-2J_\\perp}`, so it decreases together with
      the temperature and stays finite at the end. Weak couplings keep the
      replicas diverse (close to independent SA runs); strong couplings make
      them move together. Unless given, both ends are chosen from the
      energy landscape by :func:`trotter_coupling_range`.

    The pair is converted to :math:`(\\beta, s)` for a system created with
    the transverse field ``gamma``.

    Args:
        cxxgraph: Ising graph, ``Dense`` or ``CSRSparse``.
        trotter (int): Trotter number M.
        num_sweeps (int): number of sweeps.
        beta_min (float, optional): initial classical inverse temperature per slice.
        beta_max (float, optional): final classical inverse temperature per slice.
        coupling_min (float, optional): initial Trotter coupling :math:`J_\\perp`.
        coupling_max (float, optional): final Trotter coupling :math:`J_\\perp`.
        gamma (float): transverse field of the system that runs the schedule.
        from_qubo (bool): the graph was converted from a BINARY model.

    Returns:
        list of cxxjij.utility.TransverseFieldSchedule, and schedule information.
    """
    landscape = {}
    if coupling_min is None or coupling_max is None:
        estimated, landscape = trotter_coupling_range(cxxgraph, from_qubo=from_qubo)
        coupling_min = estimated[0] if coupling_min is None else coupling_min
        coupling_max = estimated[1] if coupling_max is None else coupling_max
    if not (0 < coupling_min and 0 < coupling_max and np.isfinite(coupling_min) and np.isfinite(coupling_max)):
        raise ValueError("coupling_min and coupling_max must be positive and finite.")
    if not gamma > 0:
        raise ValueError("gamma must be positive.")

    classical, beta_range = geometric_ising_beta_schedule(
        cxxgraph,
        beta_max=beta_max,
        beta_min=beta_min,
        num_sweeps=num_sweeps,
        from_qubo=from_qubo,
        use_quantiles=True,
    )

    steps = np.array([x.one_mc_step for x in classical], dtype=np.int64)
    beta_cl = np.array([x.updater_parameter.beta for x in classical], dtype=float)
    first_sweep = np.cumsum(steps) - steps
    # 0 at the first and 1 at the last schedule entry (entries may group sweeps).
    fraction = first_sweep / max(first_sweep[-1], 1) if len(first_sweep) else first_sweep
    coupling = coupling_min * (coupling_max / coupling_min) ** fraction

    # beta * gamma * (1 - s) / M such that the coupling is J_perp.
    quantum = np.arctanh(np.exp(-2.0 * coupling)) / gamma
    with np.errstate(over="ignore"):
        beta_per_slice = beta_cl + quantum
        s = beta_cl / beta_per_slice
        beta = np.minimum(trotter * beta_per_slice, np.finfo(float).max)

    schedule = []
    for b, x, n in zip(beta, s, steps):
        item = cxxjij.utility.TransverseFieldSchedule()
        item.one_mc_step = int(n)
        item.updater_parameter.beta = float(b)
        item.updater_parameter.s = float(x)
        schedule.append(item)

    info = {
        "beta_max": beta_range[0],
        "beta_min": beta_range[1],
        "coupling_min": coupling_min,
        "coupling_max": coupling_max,
        "trotter": trotter,
        "num_sweeps": num_sweeps,
        **landscape,
    }
    return schedule, info


def linear_ising_schedule(model, beta, gamma, num_sweeps):
    """Generate linear ising schedule.

    Args:
        model (:class:`openjij.model.model.BinaryQuadraticModel`): BinaryQuadraticModel
        beta (float): inverse temperature
        gamma (float): transverse field
        num_sweeps (int): number of steps
    Returns:
        generated schedule
    """
    schedule = cxxjij.utility.make_transverse_field_schedule_list(
        beta=beta, one_mc_step=1, num_call_updater=num_sweeps
    )
    return schedule, [beta, gamma]


def quartic_ising_schedule(model, beta, gamma, num_sweeps):
    """Generate quartic ising schedule based on S

    Morita and H. Nishimori,
    Journal of Mathematical Physics 49, 125210 (2008).

    Args:
        model (:class:`openjij.model.model.BinaryQuadraticModel`): BinaryQuadraticModel
        beta (float): inverse temperature
        gamma (float): transverse field
        num_sweeps (int): number of steps
    Returns:
        generated schedule
    """

    s = np.linspace(0, 1, num_sweeps)
    fs = s**4 * (35 - 84 * s + 70 * s**2 - 20 * s**3)
    schedule = [((beta, elem), 1) for elem in fs]
    return schedule, [beta, gamma]
